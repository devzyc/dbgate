#!/bin/bash

set -euo pipefail


# ============================================================
# DbGate：
# 本地源码构建
# → 本地 Docker 镜像构建
# → docker save
# → SCP 上传到 BCC
# → BCC docker load
# → 启动 DbGate
#
# 所有步骤均为同步阻塞执行。
# ============================================================


# ============================================================
# 1. 本地配置
# ============================================================

LOCAL_PROJECT="/Users/zyc/auto-complete_db_editor/DbGate"

IMAGE_NAME="tk_web_custom"
IMAGE_TAG="latest"
IMAGE_FULL_NAME="${IMAGE_NAME}:${IMAGE_TAG}"

LOCAL_TAR="${LOCAL_PROJECT}/docker/${IMAGE_NAME}.tar"


# ============================================================
# 2. BCC 配置
# ============================================================

BCC_HOST="106.13.18.150"
BCC_USER="root"

BCC_WORK_DIR="/root/tk_web/docker"

REMOTE_TAR="${BCC_WORK_DIR}/${IMAGE_NAME}.tar"


# ============================================================
# 3. DbGate 容器配置
# ============================================================

CONTAINER_NAME="tk_web_container"

HOST_PORT="3000"
CONTAINER_PORT="3000"


# ============================================================
# 辅助函数
# ============================================================

log_step() {
    echo
    echo "============================================================"
    echo "$1"
    echo "============================================================"
    echo
}


# ============================================================
# 4. 检查本地工具
# ============================================================

log_step "检查本地工具"

command -v yarn >/dev/null 2>&1 || {
    echo "错误：找不到 yarn"
    exit 1
}

command -v docker >/dev/null 2>&1 || {
    echo "错误：找不到 docker"
    exit 1
}

command -v ssh >/dev/null 2>&1 || {
    echo "错误：找不到 ssh"
    exit 1
}

command -v scp >/dev/null 2>&1 || {
    echo "错误：找不到 scp"
    exit 1
}


# ============================================================
# 5. 进入 DbGate 项目
# ============================================================

log_step "进入 DbGate 项目"

cd "$LOCAL_PROJECT"


# ============================================================
# 6. 安装 / 更新本地依赖
# ============================================================

log_step "执行 yarn"

yarn

rm -rf packages/web/public/build

# ============================================================
# 7. 构建 DbGate Docker 部署产物
# ============================================================

log_step "执行 yarn prepare:docker"

yarn prepare:docker


# ============================================================
# 8. 检查 Docker 构建材料
# ============================================================

log_step "检查 Docker 构建材料"

test -f "${LOCAL_PROJECT}/docker/Dockerfile"
test -f "${LOCAL_PROJECT}/docker/bundle.js"
test -d "${LOCAL_PROJECT}/docker/public"


# ============================================================
# 9. 本地构建 Docker 镜像
# ============================================================

log_step "构建 Docker 镜像"

docker build \
    -t "$IMAGE_FULL_NAME" \
    "${LOCAL_PROJECT}/docker"


# ============================================================
# 10. 检查镜像
# ============================================================

log_step "检查 Docker 镜像"

docker image inspect "$IMAGE_FULL_NAME" >/dev/null

docker images "$IMAGE_NAME"


# ============================================================
# 11. 导出 Docker 镜像
# ============================================================

log_step "导出 Docker 镜像"

rm -f "$LOCAL_TAR"

docker save \
    -o "$LOCAL_TAR" \
    "$IMAGE_FULL_NAME"


# ============================================================
# 12. 检查 TAR
# ============================================================

log_step "检查 TAR 文件"

test -s "$LOCAL_TAR"

ls -lh "$LOCAL_TAR"


# ============================================================
# 13. 确保 BCC 工作目录存在
# ============================================================

log_step "检查 BCC 工作目录"

ssh "${BCC_USER}@${BCC_HOST}" \
    "mkdir -p '${BCC_WORK_DIR}'"


# ============================================================
# 14. 上传 TAR
# ============================================================

log_step "通过 SCP 上传 Docker 镜像"

scp -o ProxyCommand=none \
    "$LOCAL_TAR" \
    "${BCC_USER}@${BCC_HOST}:${REMOTE_TAR}"


# ============================================================
# 15. 检查远程 TAR
# ============================================================

log_step "检查 BCC 上的 TAR"

ssh "${BCC_USER}@${BCC_HOST}" \
    "test -s '${REMOTE_TAR}' && ls -lh '${REMOTE_TAR}'"


# ============================================================
# 16. 加载 Docker 镜像
# ============================================================

log_step "BCC 加载 Docker 镜像"

ssh "${BCC_USER}@${BCC_HOST}" \
    "docker load -i '${REMOTE_TAR}'"


# ============================================================
# 17. 检查镜像是否加载成功
# ============================================================

log_step "检查 BCC Docker 镜像"

ssh "${BCC_USER}@${BCC_HOST}" \
    "docker images '${IMAGE_NAME}'"


# ============================================================
# 18. 停止旧容器
# ============================================================

log_step "停止旧 DbGate 容器"

ssh "${BCC_USER}@${BCC_HOST}" \
    "docker stop '${CONTAINER_NAME}' 2>/dev/null || true"


# ============================================================
# 19. 删除旧容器
# ============================================================

log_step "删除旧 DbGate 容器"

ssh "${BCC_USER}@${BCC_HOST}" \
    "docker rm '${CONTAINER_NAME}' 2>/dev/null || true"


# ============================================================
# 20. 启动新容器
# ============================================================

log_step "启动新的 DbGate 容器"

ssh "${BCC_USER}@${BCC_HOST}" "
    docker run -d \
        --name '${CONTAINER_NAME}' \
        --restart unless-stopped \
        -p '${HOST_PORT}:${CONTAINER_PORT}' \
        '${IMAGE_FULL_NAME}'
"


# ============================================================
# 21. 检查容器
# ============================================================

log_step "检查 DbGate 容器"

ssh "${BCC_USER}@${BCC_HOST}" "
    docker ps \
        --filter 'name=${CONTAINER_NAME}' \
        --format 'table {{.Names}}\t{{.Status}}\t{{.Ports}}'
"


# ============================================================
# 22. 查看最近日志
# ============================================================

log_step "查看 DbGate 日志"

ssh "${BCC_USER}@${BCC_HOST}" \
    "docker logs --tail 50 '${CONTAINER_NAME}'"


# ============================================================
# 23. 完成
# ============================================================

log_step "部署完成"

echo "Docker 镜像：${IMAGE_FULL_NAME}"
echo "容器名称：${CONTAINER_NAME}"
echo "BCC：${BCC_HOST}"
echo "端口：${HOST_PORT}"

echo
echo "浏览器访问："
echo "http://${BCC_HOST}:${HOST_PORT}"